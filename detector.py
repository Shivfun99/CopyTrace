import sys
import os
import time
import cv2
import numpy as np

BLOCK = 16
STRIDE = 4
FEATURES = 15
NEIGHBORS = 14
MIN_PAIRS = 12

def frequency_positions():
    positions = []
    s = 1
    while len(positions) < FEATURES:
        for k in range(s + 1):
            if len(positions) >= FEATURES:
                break
            x = k if s % 2 == 0 else s - k
            y = s - x
            positions.append((x, y))
        s += 1
    return positions

def preprocess_image(bgr, max_dimension=768):
    if bgr is None or max_dimension < 1:
        raise ValueError("Invalid image for preprocessing")
    if len(bgr.shape) == 3 and bgr.shape[2] == 3:
        gray = cv2.cvtColor(bgr, cv2.COLOR_BGR2GRAY)
    elif len(bgr.shape) == 3 and bgr.shape[2] == 4:
        gray = cv2.cvtColor(bgr, cv2.COLOR_BGRA2GRAY)
    elif len(bgr.shape) == 2:
        gray = bgr.copy()
    else:
        raise ValueError("Unsupported number of image channels")

    h, w = gray.shape[:2]
    largest = max(h, w)
    if largest > max_dimension:
        scale = max_dimension / largest
        new_w = max(1, int(round(w * scale)))
        new_h = max(1, int(round(h * scale)))
        gray = cv2.resize(gray, (new_w, new_h), interpolation=cv2.INTER_AREA)
    return gray

def covers_region_blocks(pairs):
    src = np.array([p['a'] for p in pairs], dtype=np.int32)
    tgt = np.array([p['b'] for p in pairs], dtype=np.int32)
    rx1, ry1, rw1, rh1 = cv2.boundingRect(src)
    rx2, ry2, rw2, rh2 = cv2.boundingRect(tgt)
    return rw1 > 20 and rh1 > 20 and rw2 > 20 and rh2 > 20

def filter_periodic_lattice_groups(groups, min_pairs=12, collinearity_threshold=0.96, max_harmonic_siblings=2):
    """
    Identifies and suppresses displacement groups generated by periodic natural or architectural
    structures (such as brick walls, fences, window columns, or floor tiles).
    When an image contains periodic textures, matching blocks occur at regular harmonic intervals
    (e.g., dx, 2*dx, 3*dx), resulting in multiple collinear displacement groups with high sibling counts.
    """
    valid_groups = {k: v for k, v in groups.items() if len(v) >= min_pairs}
    if len(valid_groups) <= 2:
        return valid_groups
    
    keys = list(valid_groups.keys())
    periodic_keys = set()
    
    for i in range(len(keys)):
        collinear_siblings = 0
        u = np.array(keys[i], dtype=float)
        nu = np.linalg.norm(u)
        if nu == 0:
            continue
        for j in range(len(keys)):
            if i == j:
                continue
            v = np.array(keys[j], dtype=float)
            nv = np.linalg.norm(v)
            if nv == 0:
                continue
            cos_sim = abs(np.dot(u, v) / (nu * nv))
            if cos_sim >= collinearity_threshold:
                collinear_siblings += 1
        if collinear_siblings > max_harmonic_siblings:
            periodic_keys.add(keys[i])
            
    filtered = {k: v for k, v in valid_groups.items() if k not in periodic_keys}
    return filtered

def detect_dct(gray, dist_threshold=0.30, min_pairs=MIN_PAIRS, deviation_threshold=12, filter_periodic=True):
    h, w = gray.shape[:2]
    mask = np.zeros((h, w), dtype=np.uint8)
    color = cv2.cvtColor(gray, cv2.COLOR_GRAY2BGR)
    visualization = np.hstack([color, color])

    if w < BLOCK or h < BLOCK:
        return {'mask': mask, 'visualization': visualization, 'candidate_pairs': 0, 'consistent_pairs': 0, 'displacement_groups': 0}

    positions = frequency_positions()
    descriptors = []
    blocks = []

    for y in range(0, h - BLOCK + 1, STRIDE):
        for x in range(0, w - BLOCK + 1, STRIDE):
            patch = gray[y:y+BLOCK, x:x+BLOCK]
            mean, deviation = cv2.meanStdDev(patch)
            if deviation[0][0] < deviation_threshold:
                continue
            patch_f = patch.astype(np.float32)
            transformed = cv2.dct(patch_f)
            # transformed[row, col] -> row = py, col = px
            desc = np.array([transformed[py, px] for px, py in positions], dtype=np.float32)
            length = np.linalg.norm(desc)
            if length < 1.0:
                continue
            desc /= length
            descriptors.append(desc)
            blocks.append((x, y))

    if len(descriptors) < min_pairs * 2:
        return {'mask': mask, 'visualization': visualization, 'candidate_pairs': 0, 'consistent_pairs': 0, 'displacement_groups': 0}

    desc_arr = np.array(descriptors, dtype=np.float32)
    flann = cv2.FlannBasedMatcher(dict(algorithm=1, trees=4), dict(checks=64))
    k_matches = min(NEIGHBORS, len(desc_arr))
    nearest = flann.knnMatch(desc_arr, desc_arr, k=k_matches)

    groups = {}
    candidate_pairs = 0

    for neighbors in nearest:
        accepted = 0
        for m in neighbors:
            a = blocks[m.queryIdx]
            b = blocks[m.trainIdx]
            if m.distance >= dist_threshold or np.hypot(a[0] - b[0], a[1] - b[1]) < 32 or (a[0], a[1]) >= (b[0], b[1]):
                continue
            shift_x = b[0] - a[0]
            shift_y = b[1] - a[1]
            group_key = (int(round(shift_x / 8.0)), int(round(shift_y / 8.0)))
            if group_key not in groups:
                groups[group_key] = []
            groups[group_key].append({'a': a, 'b': b, 'dist': m.distance})
            candidate_pairs += 1
            accepted += 1
            if accepted == 3:
                break

    displacement_groups = 0
    verified = []
    occ_rows = (h - BLOCK) // STRIDE + 1
    occ_cols = (w - BLOCK) // STRIDE + 1

    target_groups = filter_periodic_lattice_groups(groups, min_pairs=min_pairs) if filter_periodic else {k: v for k, v in groups.items() if len(v) >= min_pairs}

    for group_key, pairs in target_groups.items():
        pairs.sort(key=lambda p: p['dist'])
        used_src = set()
        used_tgt = set()
        distinct = []
        occupied = np.zeros((occ_rows, occ_cols), dtype=np.uint8)

        for p in pairs:
            a = p['a']
            b = p['b']
            if a in used_src or b in used_tgt:
                continue
            used_src.add(a)
            used_tgt.add(b)
            distinct.append(p)
            occupied[a[1] // STRIDE, a[0] // STRIDE] = 255

        if len(distinct) < min_pairs:
            continue

        num_labels, labels = cv2.connectedComponents(occupied, connectivity=8)
        components = [[] for _ in range(num_labels)]
        for p in distinct:
            lbl = labels[p['a'][1] // STRIDE, p['a'][0] // STRIDE]
            components[lbl].append(p)

        kept_group = False
        for lbl in range(1, num_labels):
            comp = components[lbl]
            if len(comp) < min_pairs or not covers_region_blocks(comp):
                continue
            kept_group = True
            verified.extend(comp)
        if kept_group:
            displacement_groups += 1

    for p in verified:
        cv2.rectangle(mask, (p['a'][0], p['a'][1]), (p['a'][0] + BLOCK, p['a'][1] + BLOCK), 255, -1)
        cv2.rectangle(mask, (p['b'][0], p['b'][1]), (p['b'][0] + BLOCK, p['b'][1] + BLOCK), 255, -1)

    step = max(1, (len(verified) + 149) // 150)
    for i in range(0, len(verified), step):
        pt_a = (verified[i]['a'][0] + BLOCK // 2, verified[i]['a'][1] + BLOCK // 2)
        pt_b = (verified[i]['b'][0] + w + BLOCK // 2, verified[i]['b'][1] + BLOCK // 2)
        cv2.line(visualization, pt_a, pt_b, (0, 220, 0), 1, cv2.LINE_AA)
        cv2.circle(visualization, pt_a, 2, (0, 255, 255), -1)
        cv2.circle(visualization, pt_b, 2, (0, 255, 255), -1)

    return {
        'mask': mask,
        'visualization': visualization,
        'candidate_pairs': candidate_pairs,
        'consistent_pairs': len(verified),
        'displacement_groups': displacement_groups
    }

def covers_region_points(points):
    if len(points) < 8:
        return False
    pts = np.array(points, dtype=np.float32)
    min_x, min_y = pts.min(axis=0)
    max_x, max_y = pts.max(axis=0)
    hull = cv2.convexHull(pts)
    area = cv2.contourArea(hull)
    return (max_x - min_x >= 20) and (max_y - min_y >= 20) and (area >= 400)

def detect_orb(gray, max_features=2500, ransac_threshold=4.0, min_inliers=8, filter_periodic=True):
    h, w = gray.shape[:2]
    mask = np.zeros((h, w), dtype=np.uint8)
    color = cv2.cvtColor(gray, cv2.COLOR_GRAY2BGR)
    visualization = np.hstack([color, color])

    if h < 32 or w < 32:
        return {'mask': mask, 'visualization': visualization, 'candidate_matches': 0, 'inliers': 0}

    orb = cv2.ORB_create(max_features)
    keypoints, descriptors = orb.detectAndCompute(gray, None)
    if descriptors is None or len(descriptors) < 8:
        return {'mask': mask, 'visualization': visualization, 'candidate_matches': 0, 'inliers': 0}

    matcher = cv2.BFMatcher(cv2.NORM_HAMMING)
    k_matches = min(12, len(descriptors))
    neighbors = matcher.knnMatch(descriptors, descriptors, k=k_matches)

    best = [-1] * len(keypoints)
    distances = [0.0] * len(keypoints)

    for i, match_list in enumerate(neighbors):
        nearest_idx = -1
        first_dist = float('inf')
        second_dist = float('inf')
        pt_i = keypoints[i].pt
        for m in match_list:
            if m.queryIdx == m.trainIdx:
                continue
            pt_train = keypoints[m.trainIdx].pt
            if np.hypot(pt_i[0] - pt_train[0], pt_i[1] - pt_train[1]) < 48:
                continue
            if nearest_idx < 0:
                nearest_idx = m.trainIdx
                first_dist = m.distance
            else:
                second_dist = m.distance
                break
        if nearest_idx >= 0 and first_dist <= 48 and first_dist < 0.8 * second_dist:
            best[i] = nearest_idx
            distances[i] = first_dist

    candidates = []
    for a in range(len(best)):
        b = best[a]
        if b <= a or best[b] != a:
            continue
        src = a
        tgt = b
        p = keypoints[src].pt
        q = keypoints[tgt].pt
        if (p[0], p[1]) > (q[0], q[1]):
            src, tgt = tgt, src
        candidates.append(cv2.DMatch(src, tgt, distances[a]))

    candidates.sort(key=lambda m: m.distance)
    source_cells = set()
    target_cells = set()
    distinct = []
    for m in candidates:
        p = keypoints[m.queryIdx].pt
        q = keypoints[m.trainIdx].pt
        sc = (int(p[0]) // 8, int(p[1]) // 8)
        tc = (int(q[0]) // 8, int(q[1]) // 8)
        if sc in source_cells or tc in target_cells:
            continue
        source_cells.add(sc)
        target_cells.add(tc)
        distinct.append(m)

    candidate_count = len(distinct)
    if candidate_count < 8:
        return {'mask': mask, 'visualization': visualization, 'candidate_matches': candidate_count, 'inliers': 0}

    src_pts = np.array([keypoints[m.queryIdx].pt for m in distinct], dtype=np.float32)
    tgt_pts = np.array([keypoints[m.trainIdx].pt for m in distinct], dtype=np.float32)

    transform, inliers = cv2.estimateAffinePartial2D(src_pts, tgt_pts, method=cv2.RANSAC,
                                                    ransacReprojThreshold=ransac_threshold, maxIters=3000,
                                                    confidence=0.995, refineIters=10)
    if transform is None or inliers is None:
        return {'mask': mask, 'visualization': visualization, 'candidate_matches': candidate_count, 'inliers': 0}

    scale = np.hypot(transform[0, 0], transform[1, 0])
    inlier_mask = inliers.flatten().astype(bool)
    if scale < 0.55 or scale > 1.8 or np.count_nonzero(inlier_mask) < min_inliers:
        return {'mask': mask, 'visualization': visualization, 'candidate_matches': candidate_count, 'inliers': 0}

    verified_src = src_pts[inlier_mask]
    verified_tgt = tgt_pts[inlier_mask]
    verified_matches = [distinct[i] for i in range(len(distinct)) if inlier_mask[i]]

    if not covers_region_points(verified_src) or not covers_region_points(verified_tgt):
        return {'mask': mask, 'visualization': visualization, 'candidate_matches': candidate_count, 'inliers': 0}

    if filter_periodic:
        # Check if verified inliers form transitive chains (A -> B -> C), characteristic of periodic lattice architecture
        chain_count = 0
        for t in verified_tgt:
            dists = np.linalg.norm(verified_src - t, axis=1)
            if np.any(dists < 16.0):
                chain_count += 1
        if chain_count >= 2:
            return {'mask': mask, 'visualization': visualization, 'candidate_matches': candidate_count, 'inliers': 0}

    for pt in verified_src:
        cv2.circle(mask, (int(round(pt[0])), int(round(pt[1]))), 13, 255, -1)
    for pt in verified_tgt:
        cv2.circle(mask, (int(round(pt[0])), int(round(pt[1]))), 13, 255, -1)

    visualization = cv2.drawMatches(gray, keypoints, gray, keypoints, verified_matches, None,
                                    matchColor=(0, 220, 0), singlePointColor=(100, 100, 100),
                                    flags=cv2.DrawMatchesFlags_NOT_DRAW_SINGLE_POINTS)

    return {
        'mask': mask,
        'visualization': visualization,
        'candidate_matches': candidate_count,
        'inliers': len(verified_matches)
    }

def localize_forgery(bgr, dct_mask, orb_mask, min_area=180):
    combined = cv2.bitwise_or(dct_mask, orb_mask)
    closing = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (9, 9))
    opening = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (3, 3))
    cleaned = cv2.morphologyEx(combined, cv2.MORPH_CLOSE, closing)
    cleaned = cv2.morphologyEx(cleaned, cv2.MORPH_OPEN, opening)

    num_labels, labels, stats, centroids = cv2.connectedComponentsWithStats(cleaned)
    final_mask = np.zeros_like(cleaned)
    boxes = []

    for i in range(1, num_labels):
        area = stats[i, cv2.CC_STAT_AREA]
        if area < min_area:
            continue
        final_mask[labels == i] = 255
        boxes.append((
            int(stats[i, cv2.CC_STAT_LEFT]),
            int(stats[i, cv2.CC_STAT_TOP]),
            int(stats[i, cv2.CC_STAT_WIDTH]),
            int(stats[i, cv2.CC_STAT_HEIGHT])
        ))

    highlighted = bgr.copy()
    highlighted[final_mask > 0] = [30, 30, 255]
    annotated = cv2.addWeighted(bgr, 0.55, highlighted, 0.45, 0)
    for x, y, bw, bh in boxes:
        cv2.rectangle(annotated, (x, y), (x + bw, y + bh), (0, 255, 255), 2)

    return {'mask': final_mask, 'annotated': annotated, 'boxes': boxes}

def evaluate_metrics(pred_mask, truth_mask):
    pred = pred_mask > 0
    truth = truth_mask > 0
    tp = np.count_nonzero(pred & truth)
    fp = np.count_nonzero(pred & ~truth)
    fn = np.count_nonzero(~pred & truth)
    precision = tp / (tp + fp) if (tp + fp) > 0 else 0.0
    recall = tp / (tp + fn) if (tp + fn) > 0 else 0.0
    f1 = (2 * precision * recall) / (precision + recall) if (precision + recall) > 0 else 0.0
    iou = tp / (tp + fp + fn) if (tp + fp + fn) > 0 else 0.0
    return {
        'tp': tp, 'fp': fp, 'fn': fn,
        'precision': precision, 'recall': recall, 'f1': f1, 'iou': iou
    }

def create_overlap_visualization(pred_mask, truth_mask):
    """
    Returns an RGB visualization of pixel localization overlap:
    - Green (0, 255, 0): True Positive (Correctly detected forged pixels)
    - Red (255, 0, 0): False Positive (Over-detected unedited pixels)
    - Yellow/Orange (255, 180, 0): False Negative (Missed forged pixels)
    - Slate Dark (30, 30, 45): True Negative (Background unedited)
    """
    pred = pred_mask > 0
    truth = truth_mask > 0
    h, w = pred_mask.shape[:2]
    vis = np.zeros((h, w, 3), dtype=np.uint8)
    vis[:] = (30, 30, 45)
    vis[~pred & truth] = (0, 180, 255)  # BGR for Yellow/Orange
    vis[pred & ~truth] = (0, 0, 255)    # BGR for Red
    vis[pred & truth] = (0, 255, 0)     # BGR for Green
    return vis

def run_detection(input_path, output_dir="results/python/run", truth_mask_path=None, filter_periodic=True):
    bgr = cv2.imread(input_path, cv2.IMREAD_COLOR)
    if bgr is None:
        raise FileNotFoundError(f"Cannot open input image: {input_path}")
    orig_h, orig_w = bgr.shape[:2]

    truth = None
    if truth_mask_path:
        raw_truth = cv2.imread(truth_mask_path, cv2.IMREAD_UNCHANGED)
        if raw_truth is None:
            raise FileNotFoundError(f"Cannot open ground-truth mask: {truth_mask_path}")
        if len(raw_truth.shape) == 3:
            truth = np.any(raw_truth[:, :, :3] != 0, axis=2).astype(np.uint8) * 255
        else:
            truth = (raw_truth != 0).astype(np.uint8) * 255

    os.makedirs(output_dir, exist_ok=True)
    start_time = time.perf_counter()

    gray = preprocess_image(bgr)
    proc_h, proc_w = gray.shape[:2]
    if (orig_w, orig_h) != (proc_w, proc_h):
        bgr = cv2.resize(bgr, (proc_w, proc_h), interpolation=cv2.INTER_AREA)
    if truth is not None and (truth.shape[1], truth.shape[0]) != (proc_w, proc_h):
        truth = cv2.resize(truth, (proc_w, proc_h), interpolation=cv2.INTER_NEAREST)

    dct_res = detect_dct(gray, filter_periodic=filter_periodic)
    orb_res = detect_orb(gray, filter_periodic=filter_periodic)
    loc_res = localize_forgery(bgr, dct_res['mask'], orb_res['mask'])
    elapsed_ms = (time.perf_counter() - start_time) * 1000.0

    cv2.imwrite(os.path.join(output_dir, "01_input.png"), bgr)
    cv2.imwrite(os.path.join(output_dir, "02_grayscale.png"), gray)
    cv2.imwrite(os.path.join(output_dir, "03_dct_mask.png"), dct_res['mask'])
    cv2.imwrite(os.path.join(output_dir, "04_orb_mask.png"), orb_res['mask'])
    cv2.imwrite(os.path.join(output_dir, "05_final_mask.png"), loc_res['mask'])
    cv2.imwrite(os.path.join(output_dir, "06_highlighted.png"), loc_res['annotated'])
    cv2.imwrite(os.path.join(output_dir, "07_orb_matches.png"), orb_res['visualization'])
    cv2.imwrite(os.path.join(output_dir, "08_dct_matches.png"), dct_res['visualization'])

    total_pixels = proc_w * proc_h
    flagged_pixels = np.count_nonzero(loc_res['mask'])
    area_percent = (100.0 * flagged_pixels) / total_pixels
    assessment = "SUSPICIOUS MATCHED REGIONS" if len(loc_res['boxes']) > 0 else "NO STRONG COPY-MOVE INDICATORS"

    report_lines = [
        "CLASSICAL DIP COPY-MOVE ANALYSIS",
        f"Image: {os.path.basename(input_path)}",
        f"Original dimensions: {orig_w} x {orig_h}",
        f"Processed dimensions: {proc_w} x {proc_h}",
        f"DCT candidate pairs: {dct_res['candidate_pairs']}",
        f"DCT consistent pairs: {dct_res['consistent_pairs']}",
        f"DCT displacement groups: {dct_res['displacement_groups']}",
        f"ORB candidate matches: {orb_res['candidate_matches']}",
        f"ORB RANSAC inliers: {orb_res['inliers']}",
        f"Suspicious connected regions: {len(loc_res['boxes'])}",
        f"Flagged area: {area_percent:.2f}%",
        f"Processing time (excluding image loading and saving): {elapsed_ms:.2f} ms",
        f"Assessment: {assessment}",
        "Bounding boxes (zero-based x y width height, processed pixels):"
    ]
    for i, box in enumerate(loc_res['boxes']):
        report_lines.append(f"  {i + 1}: {box[0]} {box[1]} {box[2]} {box[3]}")
    report_lines.append("Both source and copied regions may be marked. Natural repeated patterns can also match.")
    report_lines.append("The result is an indicator, not proof of manipulation.")

    scores = None
    if truth is not None:
        scores = evaluate_metrics(loc_res['mask'], truth)
        report_lines.extend([
            f"Ground-truth mask: {os.path.basename(truth_mask_path)}",
            "Evaluation uses processed pixels and nearest-neighbor truth resizing.",
            "Zero denominators produce a score of 0, including two empty masks.",
            f"TP: {scores['tp']} FP: {scores['fp']} FN: {scores['fn']}",
            f"Precision: {scores['precision']:.4f}",
            f"Recall: {scores['recall']:.4f}",
            f"F1: {scores['f1']:.4f}",
            f"IoU: {scores['iou']:.4f}"
        ])
    else:
        report_lines.append("Evaluation: no ground-truth mask supplied.")

    report_path = os.path.join(output_dir, "report.txt")
    with open(report_path, "w", encoding="utf-8") as f:
        f.write("\n".join(report_lines) + "\n")

    print(f"\n{assessment}")
    print(f"DCT consistent pairs: {dct_res['consistent_pairs']}")
    print(f"ORB inliers: {orb_res['inliers']}")
    print(f"Suspicious regions: {len(loc_res['boxes'])}")
    print(f"Flagged area: {area_percent:.2f}%")
    print(f"Elapsed time: {elapsed_ms:.2f} ms")
    if scores:
        print(f"Precision: {scores['precision']:.4f}")
        print(f"Recall: {scores['recall']:.4f}")
        print(f"F1: {scores['f1']:.4f}")
        print(f"IoU: {scores['iou']:.4f}")
    print(f"Results saved in: {os.path.abspath(output_dir)}")

if __name__ == "__main__":
    if len(sys.argv) < 2 or sys.argv[1] in ("-h", "--help"):
        print("Usage: python detector.py <input_image> [output_folder] [truth_mask]")
        sys.exit(0)
    input_img = sys.argv[1]
    out_dir = sys.argv[2] if len(sys.argv) >= 3 else "results/run"
    mask_file = sys.argv[3] if len(sys.argv) >= 4 else None
    run_detection(input_img, out_dir, mask_file)
